BIG, SMALL, GAP = 12, 2, 28
CELL = 16 * BIG


def rgb(colour: str) -> bytes:
    return bytes.fromhex(colour[1:])


def main() -> None:
    width = GAP + len(MASCOTS) * (CELL + GAP)
    height = GAP + CELL + GAP + 16 * SMALL + GAP
    pixels = [[rgb(BACKGROUND)] * width for _ in range(height)]
    for number, (name, art) in enumerate(MASCOTS.items()):
        rows = art.strip("\n").split("\n")
        assert len(rows) == 16 and all(len(row) == 16 for row in rows), name
        left = GAP + number * (CELL + GAP)
        for y in range(GAP - 8, GAP + CELL + 8):      # a plate behind the large drawing
            for x in range(left - 8, left + CELL + 8):
                pixels[y][x] = rgb(PLATE)
        for size, ox, oy in ((BIG, left, GAP), (SMALL, left + (CELL - 16 * SMALL) // 2, GAP + CELL + GAP)):
            for row, line in enumerate(rows):
                for column, letter in enumerate(line):
                    if letter != ".":
                        for y in range(size):
                            for x in range(size):
                                pixels[oy + row * size + y][ox + column * size + x] = rgb(LETTERS[letter])

    def chunk(kind: bytes, body: bytes) -> bytes:
        return struct.pack(">I", len(body)) + kind + body + struct.pack(">I", zlib.crc32(kind + body))

    data = b"".join(b"\x00" + b"".join(row) for row in pixels)
    out = Path(__file__).with_name("mascots.png")
    out.write_bytes(b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0))
                    + chunk(b"IDAT", zlib.compress(data, 9)) + chunk(b"IEND", b""))
    print(out)


def save_chosen(name: str, scale: int = 8) -> None:
    """The chosen mascot on its own, with a see-through background, for the window.

    Saved already enlarged (8 times, so 128 by 128) with hard pixel edges. The window shows
    it at 32 pixels with normal smoothing: at rest each art pixel lands exactly on 2 by 2
    screen pixels and looks crisp, and while it moves or squashes the smoothing keeps the
    motion fluid. From a 16-pixel file shown "pixelated", every frame of a move snapped to
    whole pixels and looked jerky (owner feedback, Nov 17, 2026).
    """
    rows = MASCOTS[name].strip("\n").split("\n")
    size = 16 * scale
    clear = b"\x00\x00\x00\x00"
    lines = []
    for line in rows:
        row = b"".join((rgb(LETTERS[letter]) + b"\xff" if letter != "." else clear) * scale for letter in line)
        lines.extend([b"\x00" + row] * scale)
    data = b"".join(lines)

    def chunk(kind: bytes, body: bytes) -> bytes:
        return struct.pack(">I", len(body)) + kind + body + struct.pack(">I", zlib.crc32(kind + body))

    out = Path(__file__).resolve().parents[1] / "ui" / "src" / "art" / "mascot.png"
    out.write_bytes(b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", size, size, 8, 6, 0, 0, 0))
                    + chunk(b"IDAT", zlib.compress(data, 9)) + chunk(b"IEND", b""))
    print(out)


